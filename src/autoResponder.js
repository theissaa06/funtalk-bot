// Авто-ответы на ключевые слова, триггеры и реакции.
// ============================================================

const { getRandom } = require('./utils');

// ── Словарь триггеров ─────────────────────────────────────────
// Формат: [regex, ответ | массив ответов]
const triggers = [
  [/\bпривет\b|\bхей\b|\bхай\b/i, [
    '👋 Привет!',
    '🎤 Хей!',
    '🔥 О, привет!',
    '✨ Приветики!',
  ]],
  [/\bкак дела\b|\bкак ты\b|\bкак сам\b/i, [
    '🍀 Всё отлично, спасибо!',
    '🤖 Работаю в штатном режиме.',
    '📋 Заряжен на 100%, как обычно.',
    '🎤 Лучше всех! А ты?',
  ]],
  [/\bспасибо\b|\bблагодарю\b|\bспс\b/i, [
    '🍀 Пожалуйста!',
    '🤝 Не за что!',
    '✨ Всегда пожалуйста!',
    '💫 Обращайся!',
  ]],
  [/\bмем\b|\bпришли мем\b/i, [
    '🎭 Я бы прислал, но авторские права...',
    '🤖 Мой внутренний мем-банк сейчас на обслуживании.',
    '🎤 Напиши /meme — дам тебе текстовый мем!',
  ]],
  [/\bскучно\b|\bнечего делать\b/i, [
    '🎲 Напиши /topic — дам тему для разговора!',
    '🎮 Брось кубик: /dice',
    '🎤 Скучно? Поговори с кем-нибудь в чате!',
    '💬 Напиши /random — получишь мудрость дня.',
  ]],
  [/\bбот\b.*\bспишь\b|\bты живой\b/i, [
    '🤖 Я всегда начеку!',
    '👁 Слежу за каждым сообщением.',
    '🎤 Боты не спят. Боты ждут.',
  ]],
  [/\bумный\b.*\bбот\b|\bклёвый\b.*\bбот\b|\bкрутой\b.*\bбот\b/i, [
    '🍀 Спасибо, стараюсь!',
    '🙏 Приятно слышать!',
    '✨ Ты тоже ничего!',
  ]],
];

function register(bot) {
  // ── Авто-ответы на триггеры ───────────────────────────────────
  bot.on('text', async (ctx, next) => {
    // Только группы + не команды
    if (ctx.chat.type === 'private') return next();
    if (ctx.message.text.startsWith('/')) return next();

    const text = ctx.message.text;

    for (const [pattern, responses] of triggers) {
      if (pattern.test(text)) {
        const reply = Array.isArray(responses)
          ? getRandom(responses)
          : responses;

        // Шанс 30% — не всегда отвечаем, чтобы не спамить
        if (Math.random() < 0.30) {
          await ctx.reply(reply);
        }
        break;
      }
    }

    return next();
  });

  console.log('✅ Модуль autoResponder подключён');
}

module.exports = { register };
