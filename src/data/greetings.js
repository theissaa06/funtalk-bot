/**
 * Возвращает случайное приветствие с подставленным именем.
 * @param {string} name — имя или @username пользователя
 * @returns {string}
 */
function getWelcomeMessage(name) {
  const template = welcomeTemplates[
    Math.floor(Math.random() * welcomeTemplates.length)
  ];
  return template.replace(/{name}/g, name);
}

/**
 * Формирует отображаемое имя пользователя из объекта Telegraf.
 * Приоритет: @username → first_name last_name → first_name → "Участник"
 * @param {object} user — объект from (ctx.message.from)
 * @returns {string}
 */
function formatUserName(user) {
  if (!user) return 'Участник';
  if (user.username) return `@${user.username}`;
  const parts = [user.first_name, user.last_name].filter(Boolean);
  return parts.length > 0 ? parts.join(' ') : 'Участник';
}

