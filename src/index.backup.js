bot.on('chat_member', async (ctx) => {
  try {
    const member = ctx.chatMember;
    if (!member) return;

    const { new_chat_member, old_chat_member } = member;

    // РќРѕРІС‹Р№ СѓС‡Р°СЃС‚РЅРёРє = СЃС‚Р°С‚СѓСЃ РёР·РјРµРЅРёР»СЃСЏ РЅР° member/restricted РёР· РґСЂСѓРіРѕРіРѕ
    const isNewMember =
      ['left', 'kicked', 'banned'].includes(old_chat_member?.status) &&
      ['member', 'restricted'].includes(new_chat_member?.status);

    if (!isNewMember) return;
    if (new_chat_member.user.is_bot) return; // РЅРµ РїСЂРёРІРµС‚СЃС‚РІСѓРµРј Р±РѕС‚РѕРІ

    const user    = new_chat_member.user;
    const name    = greetings.formatUserName(user);
    const message = greetings.getWelcomeMessage(name);

    await ctx.reply(message, { parse_mode: 'Markdown' });
  } catch (err) {
    console.error('[welcome]', err.message);
  }
});

// Fallback: РЅРµРєРѕС‚РѕСЂС‹Рµ Р±РѕС‚С‹ РїРѕР»СѓС‡Р°СЋС‚ new_chat_members С‡РµСЂРµР· message
bot.on('message', async (ctx, next) => {
  if (!ctx.message?.new_chat_members) return next();

  for (const user of ctx.message.new_chat_members) {
    if (user.is_bot) continue;
    try {
      const name    = greetings.formatUserName(user);
      const message = greetings.getWelcomeMessage(name);
      await ctx.reply(message, { parse_mode: 'Markdown' });
    } catch (err) {
      console.error('[welcome_fallback]', err.message);
    }
  }

  return next();
});

