require('dotenv').config();

const { Telegraf } = require('telegraf');

const chatId = process.argv[2] || process.env.ANNOUNCE_CHAT_ID;

const text = [
  '<b>Funtalchik обновляется!</b>',
  '',
  'Привет! Спешим поделиться: бот скоро станет намного интереснее. Вот что уже готовится:',
  '',
  '<b>Модерация станет удобнее</b>',
  'Админам больше не придётся вручную вводить сложные команды: время мута или бана можно будет выбрать кнопкой. Появится журнал действий модераторов и возможность пожаловаться на нарушителя прямо в чате.',
  '',
  '<b>Достижения и награды</b>',
  'За активность, победы в играх и разные события в чате можно будет получать значки-достижения: от обычных до легендарных. А ещё будут красивые уведомления, когда вы что-то получаете.',
  '',
  '<b>Магазин</b>',
  'В магазине появятся лутбоксы, подарки друзьям и продажа ненужных предметов обратно.',
  '',
  '<b>Игры прямо в чате</b>',
  'Добавим “Города”, “Мафию” с ролями и голосованием, а также быстрые мини-игры на реакцию и удачу.',
  '',
  '<b>Топ участников</b>',
  'Рейтинг активных участников можно будет закрепить в чате, и он будет обновляться сам.',
  '',
  '<b>Мемы по пятницам</b>',
  'Каждую пятницу бот сможет присылать подборку мемов для настроения.',
  '',
  '<b>Скачивание видео</b>',
  'Кинул ссылку на TikTok или YouTube — бот сам пришлёт видео прямо в чат.',
  '',
  '<b>Поддержка</b>',
  'Если что-то не работает или есть вопрос к разработчику, можно будет написать прямо через бота.',
  '',
  'Спасибо, что вы с нами — скоро всё это появится в чате!',
].join('\n');

async function main() {
  if (!process.env.BOT_TOKEN) {
    throw new Error('BOT_TOKEN is required');
  }
  if (!chatId) {
    throw new Error('ANNOUNCE_CHAT_ID is required. Pass chat id as the first argument or set ANNOUNCE_CHAT_ID.');
  }

  const bot = new Telegraf(process.env.BOT_TOKEN);
  await bot.telegram.sendMessage(chatId, text, { parse_mode: 'HTML' });
  console.log(`Announcement sent to chat ${chatId}.`);
}

main().catch(error => {
  console.error(`Announcement failed: ${error.message}`);
  process.exit(1);
});
